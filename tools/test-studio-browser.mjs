await page.getByRole('button',{name:'Liked',exact:true}).waitFor();
// Reimport two rows to exercise independent working buffers across full renders.
await page.getByText('Import RSS / Atom file (CORS fallback)').click();
await page.getByLabel('Original feed URL').fill('https://feed.example/rss.xml');
await page.getByLabel('Feed file',{exact:true}).setInputFiles({name:'two.xml',mimeType:'application/xml',buffer:Buffer.from('<rss version="2.0"><channel><title>Example feed</title><link>https://feed.example/</link><description>Feed</description><item><guid>post-one</guid><title>One</title><description>One</description></item><item><guid>post-two</guid><title>Two</title><description>Two</description></item></channel></rss>')});
await page.getByRole('button',{name:'Import feed',exact:true}).click();
const notes = page.getByLabel('Private note',{exact:true});
await notes.nth(1).waitFor();
await notes.nth(0).fill('Saved A');
await notes.nth(1).fill('Unsaved B');
assert.equal(await page.evaluate(() => { const e = new Event('beforeunload',{cancelable:true}); window.dispatchEvent(e); return e.defaultPrevented; }),true);
// Programmatic activation keeps the editing field focused during an async render.
const originalNote = await notes.nth(1).elementHandle();
await notes.nth(1).evaluate(el => { el.focus(); el.setSelectionRange(2,6); document.querySelector('#reader button').click(); });
await page.waitForFunction(el => !el.isConnected,originalNote);
await originalNote.dispose();
await page.getByText('Saved in this browser.',{exact:true}).waitFor();
assert.deepEqual(await notes.nth(1).evaluate(el => [document.activeElement === el,el.selectionStart,el.selectionEnd]),[true,2,6]);
await page.getByRole('button',{name:'Save private note',exact:true}).nth(0).click();
await page.getByText('Saved in this browser.',{exact:true}).waitFor();
assert.equal(await notes.nth(1).inputValue(),'Unsaved B');
await page.locator('#reader article').nth(0).getByRole('button',{name:/^(Like|Liked)$/}).click();
await page.getByText('Saved in this browser.',{exact:true}).waitFor();
