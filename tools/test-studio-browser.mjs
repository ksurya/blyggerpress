import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';
const browser = await chromium.launch({...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH} : {})});
const page = await browser.newPage({viewport:{width:1280,height:900}});
page.on('console',m => { if(m.type() === 'error') console.log('BROWSER',m.text()); });
page.on('pageerror',e => console.log('PAGE ERROR',e.message));
await page.goto(pathToFileURL(resolve('dist/index.html')).href);
await page.getByLabel('Publication URL').fill('https://example.com/blyg/');
await page.getByLabel('Title',{exact:true}).fill('My blyg');
await page.getByRole('button',{name:'Save publication settings'}).click();
await page.getByText('Saved in this browser.',{exact:true}).waitFor();
await page.getByRole('button',{name:'Write',exact:true}).click();
await page.getByRole('button',{name:'New fragment',exact:true}).click();
await page.getByLabel('Markdown',{exact:true}).fill('A small place to write.\n\nHello **world**.');
await page.getByRole('button',{name:'Preview',exact:true}).click();
await page.getByText('Saved in this browser.',{exact:true}).waitFor();
await page.frameLocator('#preview-frame').getByText('Hello world.').waitFor();
await page.screenshot({path:'.context/studio-laptop.png',fullPage:true});
await page.getByRole('button',{name:'Publish version locally',exact:true}).click();
await page.getByText('1 versions').waitFor();
await page.reload();
await page.getByText('1 versions').waitFor();
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Preview item',exact:true}).click();
await page.frameLocator('#preview-frame').getByText('Hello world.').waitFor();
await page.screenshot({path:'.context/studio-phone.png',fullPage:true});
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
await page.evaluate(() => { document.getElementById('export').addEventListener('click',() => console.log('export clicked')); });
const downloading = page.waitForEvent('download',{timeout:10000});
await page.getByRole('button',{name:'Download public site ZIP'}).click();
const download = await downloading.catch(async error => { console.error('Download status:',await page.locator('#status').textContent()); await page.screenshot({path:'.context/download-failure.png',fullPage:true}); await browser.close(); throw error; });
assert.equal(download.suggestedFilename(),'blyg-site.zip');
assert.equal(await download.failure(),null);

await page.getByRole('button',{name:'Read',exact:true}).click();
await page.getByText('Import RSS / Atom file (CORS fallback)').click();
await page.getByLabel('Original feed URL').fill('https://feed.example/rss.xml');
await page.getByLabel('Feed file',{exact:true}).setInputFiles({name:'feed.xml',mimeType:'application/xml',buffer:Buffer.from('<rss version="2.0"><channel><title>Example feed</title><link>https://feed.example/</link><description>Feed</description><item><guid>post-one</guid><title>Post one</title><description>Read me</description><link>https://feed.example/one</link></item></channel></rss>')});
await page.getByRole('button',{name:'Import feed',exact:true}).click();
await page.getByLabel('Private note',{exact:true}).fill('Private browser note');
await page.getByRole('button',{name:'Save private note',exact:true}).click();
await page.getByText('Saved in this browser.',{exact:true}).waitFor();
await page.getByRole('button',{name:'Like',exact:true}).click();
await page.getByRole('button',{name:'Liked',exact:true}).waitFor();
await page.reload();
await page.getByRole('button',{name:'Read',exact:true}).click();
assert.equal(await page.getByLabel('Private note',{exact:true}).inputValue(),'Private browser note');
await page.getByRole('button',{name:'Liked',exact:true}).waitFor();
console.log('Standalone Chromium check passed: preview, publish, reload, mobile layout, ZIP download, feed import, private note and feedback persistence.');
await page.close();
await browser.close();
