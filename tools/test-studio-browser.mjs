await page.route('https://feed.example/**', route => route.fulfill({contentType:'application/rss+xml',body:'<rss version="2.0"><channel><title>Example feed</title><link>https://feed.example/</link><description>Feed</description><item><guid>post-one</guid><title>One</title><description>Updated</description></item><item><guid>post-two</guid><title>Two</title><description>Two</description></item></channel></rss>'}));
