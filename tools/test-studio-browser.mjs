await guard.dismiss();
await reloading;
assert.equal(await page.getByLabel('Title',{exact:true}).inputValue(),'Unsaved identity');
// Canceled restore retains all working inputs; accepted restore clears them.
const backingUp = page.waitForEvent('download');
