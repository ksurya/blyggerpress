assert.equal(await page.getByLabel('Markdown',{exact:true}).inputValue(),'Unsaved editor');
// Consent to switch does not clear dirty state if persistence fails.
await page.evaluate(() => { window.originalPut = IDBObjectStore.prototype.put; IDBObjectStore.prototype.put = function () { throw new Error('Injected write failure'); }; });
page.once('dialog', dialog => dialog.accept());
await page.getByRole('button',{name:'New thread',exact:true}).click();
await page.locator('#status.error').waitFor();
assert.match(await page.locator('#status').textContent(),/Injected write failure/);
await page.evaluate(() => { IDBObjectStore.prototype.put = window.originalPut; delete window.originalPut; });
assert.equal(await page.locator('#drafts button').count(),count);
assert.equal(await page.getByLabel('Markdown',{exact:true}).inputValue(),'Unsaved editor');
// Dirty editor still requires consent after the failed operation.
